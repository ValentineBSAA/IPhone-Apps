import XCTest
@testable import LastSeen

@MainActor final class VeilCommunityTests:XCTestCase {
    func testBackNavigationSkipsUnavailableServices() {
        var state=RestoredPhoneBackup.snapshot()
        state.flags.formUnion(["phone-tutorial-finished","web.visited.archive",VeilArchive.discovery])
        let (target,remaining)=VeilArchive.backTarget(["directory","records","home-index","invalid"],in:state)
        XCTAssertEqual(target?.id,"records")
        XCTAssertEqual(remaining,["directory"])
        state.everydayArchiveRevision=nil
        let (revoked,empty)=VeilArchive.backTarget(["directory","records"],in:state)
        XCTAssertNil(revoked)
        XCTAssertTrue(empty.isEmpty)
    }
    func testRecoveredReferencesAndPageBookmarks() {
        var state=RestoredPhoneBackup.snapshot()
        XCTAssertTrue(VeilReferences.visible(state).isEmpty)
        state.flags.formUnion(["phone-tutorial-finished","web.visited.archive",VeilArchive.discovery])
        let store=PhoneWorldStore(initial:state,persistToDisk:false)
        XCTAssertEqual(VeilReferences.visible(store.state).count,1)
        store.inspectVeilReference("private-index-reference")
        XCTAssertNil(VeilReferences.target("private-index-reference",in:store.state))
        store.inspectVeilReference("directory-reference")
        let directory=VeilReferences.target("directory-reference",in:store.state)
        XCTAssertNotNil(directory)
        XCTAssertTrue(directory?.address.contains(".invalid/") ?? false)
        XCTAssertNil(VeilArchive.resolve("https://example.com",in:store.state))
        XCTAssertNil(VeilArchive.resolve("veil://fragment-04",in:store.state))
        store.toggleVeilPageBookmark("directory",packages:"veil",safeMode:false)
        XCTAssertEqual(VeilArchive.pageBookmarkIDs(store.state),["directory"])
        state=store.state;state.flags.insert("web.visited.archive-ledger")
        let later=PhoneWorldStore(initial:state,persistToDisk:false)
        XCTAssertNil(VeilReferences.target("private-index-reference",in:later.state))
        later.inspectVeilReference("private-index-reference")
        let target=VeilReferences.target("private-index-reference",in:later.state)
        XCTAssertNotNil(target)
        XCTAssertFalse(VeilArchive.directoryPages(later.state).contains{$0.id=="fragment-04"})
        XCTAssertEqual(VeilArchive.resolve(target?.address ?? "",in:later.state)?.id,"fragment-04")
        XCTAssertFalse(VeilArchive.allowsImages("Safest"))
        XCTAssertFalse(VeilArchive.allowsImages("unknown"))
        XCTAssertTrue(VeilArchive.allowsImages("Safer"))
    }
    func testSecondaryIndexRequiresMeaningfulSavedComparisonAndExplicitInspection() throws {
        var state = RestoredPhoneBackup.snapshot()
        state.flags.formUnion(["phone-tutorial-finished","web.visited.archive",VeilArchive.discovery])
        let w = PhoneWorldStore(initial:state,persistToDisk:false)
        w.recordVeilCorrespondenceOpened()
        w.inspectVeilReference("board-reference")
        w.recordVeilObservation("Nora_Archive_08")
        w.inspectVeilReference(VeilReferences.homeIndexID)
        XCTAssertFalse(w.state.flags.contains(VeilReferences.marker(VeilReferences.homeIndexID)))
        for asset in VeilArchive.homeAssets.prefix(2) {
            w.recordVeilObservation(asset)
            XCTAssertTrue(w.completeRecoveredImageAnalysis(asset,source:2,limit:0))
        }
        let image = "image:VEIL_Home_01", thread = "veil:thread:ordinary-hours"
        XCTAssertFalse(w.saveEvidenceConnection(image,thread,relation:.wording))
        w.recordVeilThreadOpened("ordinary-hours",packages:"veil",safeMode:false)
        XCTAssertTrue(w.saveEvidenceConnection(image,thread,relation:.source))
        XCTAssertFalse(VeilReferences.homeIndexReady(w.state))
        XCTAssertTrue(w.saveEvidenceConnection(thread,image,relation:.wording))
        XCTAssertTrue(VeilReferences.homeIndexReady(w.state))
        XCTAssertNil(VeilReferences.target(VeilReferences.homeIndexID,in:w.state))
        w.recordVeilHomeIndexOpened()
        XCTAssertNil(LumaAssistantEvidence.selected("veil:home-index",in:w.state))
        w.inspectVeilReference(VeilReferences.homeIndexID)
        let page = try XCTUnwrap(VeilReferences.target(VeilReferences.homeIndexID,in:w.state))
        XCTAssertNil(VeilArchive.resolve("home-index",in:w.state))
        XCTAssertFalse(VeilArchive.directoryPages(w.state).contains{$0.id == page.id})
        XCTAssertEqual(VeilArchive.resolve(page.address,in:w.state)?.id,page.id)
        XCTAssertNil(LumaAssistantEvidence.selected("veil:home-index",in:w.state))
        XCTAssertNil(VeilCommunity.thread("first-copy",in:w.state))
        w.recordVeilHomeIndexOpened()
        XCTAssertNotNil(LumaAssistantEvidence.selected("veil:home-index",in:w.state))
        XCTAssertEqual(VeilCommunity.visible(w.state).count,17)
        XCTAssertEqual(VeilCommunity.visible(w.state).flatMap(\.replies).count,51)
        XCTAssertFalse(w.recordVeilDispute(0,packages:"veil",safeMode:false))
        w.recordVeilThreadOpened("first-copy",packages:"veil",safeMode:false)
        XCTAssertFalse(w.recordVeilDispute(0,packages:"veil",safeMode:false))
        w.recordVeilThreadOpened("second-copy",packages:"veil",safeMode:false)
        XCTAssertFalse(w.recordVeilDispute(1,packages:"veil",safeMode:false))
        XCTAssertFalse(w.recordVeilDispute(2,packages:"veil",safeMode:false))
        XCTAssertFalse(w.recordVeilDispute(0,packages:"",safeMode:false))
        XCTAssertFalse(w.recordVeilDispute(0,packages:"veil",safeMode:true))
        XCTAssertTrue(w.recordVeilDispute(0,packages:"veil",safeMode:false))
        XCTAssertTrue(w.recordVeilDispute(0,packages:"veil",safeMode:false))
        XCTAssertTrue(VeilCommunity.disputeReviewed(w.state))
        XCTAssertTrue(LumaAssistantEvidence.selected("veil:home-index",in:w.state)?.excerpts.contains(VeilCommunity.disputeNote) ?? false)
        w.toggleVeilPageBookmark(page.id,packages:"veil",safeMode:false)
        XCTAssertTrue(VeilArchive.directoryPages(w.state).contains{$0.id == page.id})
        let restored = try JSONDecoder().decode(PhoneWorld.self,from:JSONEncoder().encode(w.state))
        XCTAssertNotNil(LumaAssistantEvidence.selected("veil:home-index",in:restored))
        XCTAssertTrue(VeilCommunity.disputeReviewed(restored))
        let pairID=[image,thread].sorted().joined(separator:"|")
        XCTAssertTrue(EvidenceConnection.revokesMilestone(pairID,in:w.state))
        var full=w.state
        var connected=full.connectedWorld ?? LumaConnectedState()
        let prerequisite=try XCTUnwrap(connected.evidenceConnections?.first{$0.id==pairID})
        // Synthetic storage-only entries exercise the capacity boundary.
        connected.evidenceConnections=(0..<39).map{.init(first:"fixture-a-\($0)",second:"fixture-b-\($0)",relation:.uncertainty)}+[prerequisite]
        full.connectedWorld=connected
        let capped=PhoneWorldStore(initial:full,persistToDisk:false)
        capped.visitWebRecord("books");capped.visitWebRecord("cafe")
        XCTAssertTrue(capped.saveEvidenceConnection("web:books","web:cafe",relation:.source))
        XCTAssertEqual(capped.connected.evidenceConnections?.count,EvidenceConnection.capacity)
        XCTAssertTrue(capped.connected.evidenceConnections?.contains(prerequisite) ?? false)
        XCTAssertTrue(VeilCommunity.disputeReviewed(capped.state))
        XCTAssertFalse(capped.saveEvidenceConnection(image,thread,relation:.uncertainty))
        XCTAssertTrue(VeilCommunity.disputeReviewed(capped.state))
        // The same stored dependency must survive capacity eviction while hidden.
        full.flags.remove(VeilArchive.discovery)
        let dormant=PhoneWorldStore(initial:full,persistToDisk:false)
        XCTAssertFalse(VeilReferences.homeIndexReady(dormant.state))
        XCTAssertFalse(EvidenceConnection.visible(dormant.state).contains(prerequisite))
        dormant.visitWebRecord("books");dormant.visitWebRecord("cafe")
        XCTAssertTrue(dormant.saveEvidenceConnection("web:books","web:cafe",relation:.source))
        XCTAssertEqual(dormant.connected.evidenceConnections?.count,EvidenceConnection.capacity)
        XCTAssertTrue(dormant.connected.evidenceConnections?.contains(prerequisite) ?? false)
        var recovered=dormant.state
        recovered.flags.insert(VeilArchive.discovery)
        XCTAssertTrue(VeilReferences.homeIndexReady(recovered))
        XCTAssertTrue(VeilCommunity.disputeReviewed(recovered))
        w.removeEvidenceConnection(pairID)
        XCTAssertNil(VeilArchive.resolve(page.address,in:w.state))
        XCTAssertNil(LumaAssistantEvidence.selected("veil:home-index",in:w.state))
        XCTAssertFalse(VeilArchive.pageBookmarkIDs(w.state).contains(page.id))
        XCTAssertFalse(VeilCommunity.disputeReviewed(w.state))
        XCTAssertNil(VeilCommunity.thread("first-copy",in:w.state))
        XCTAssertNil(LumaAssistantEvidence.selected("veil:thread:second-copy",in:w.state))
    }
    func testCatalogAndAccess() {
        var world=RestoredPhoneBackup.snapshot()
        XCTAssertTrue(VeilCommunity.visible(world).isEmpty)
        world.flags.formUnion(["phone-tutorial-finished","web.visited.archive",VeilArchive.discovery])
        XCTAssertTrue(VeilCommunity.visible(world).isEmpty)
        XCTAssertNil(VeilArchive.resolve("boards",in:world))
        world.flags.insert("veil.correspondence.opened")
        let discover=PhoneWorldStore(initial:world,persistToDisk:false)
        discover.inspectVeilReference("board-reference")
        world=discover.state
        XCTAssertEqual(VeilCommunity.visible(world).count,11)
        XCTAssertNotNil(VeilArchive.resolve("boards",in:world))
        XCTAssertNil(VeilCommunity.thread("image-index",in:world))
        for id in ["ordinary-hours","favorite-frame","not-a-relationship"] {
            XCTAssertNil(VeilCommunity.thread(id,in:world))
        }
        world.flags.insert("veil.viewed.Nora_Archive_08")
        let threads=VeilCommunity.visible(world)
        XCTAssertEqual(threads.count,15)
        XCTAssertEqual(Set(threads.map(\.id)).count,15)
        XCTAssertEqual(threads.flatMap(\.replies).count,45)
        for id in ["ordinary-hours","favorite-frame","not-a-relationship"] {
            XCTAssertNotNil(VeilCommunity.thread(id,in:world))
            XCTAssertNil(LumaAssistantEvidence.selected("veil:thread:"+id,in:world))
        }
        XCTAssertTrue(threads.allSatisfy{VeilCommunity.handles.contains($0.author) && $0.replies.allSatisfy{VeilCommunity.handles.contains($0.author)}})
        let store=PhoneWorldStore(initial:world,persistToDisk:false)
        store.recordVeilThreadOpened("quiet-tapes",packages:"",safeMode:false)
        XCTAssertTrue(VeilCommunity.opened(store.state).isEmpty)
        store.recordVeilThreadOpened("quiet-tapes",packages:"veil",safeMode:false)
        XCTAssertEqual(VeilCommunity.opened(store.state).map(\.id),["quiet-tapes"])
        XCTAssertNotNil(LumaAssistantEvidence.selected("veil:thread:quiet-tapes",in:store.state))
        store.toggleVeilThreadBookmark("quiet-tapes",packages:"veil",safeMode:false)
        XCTAssertEqual(VeilCommunity.bookmarkIDs(store.state),["quiet-tapes"])
        store.toggleVeilThreadBookmark("quiet-tapes",packages:"veil",safeMode:true)
        XCTAssertEqual(VeilCommunity.bookmarkIDs(store.state),["quiet-tapes"])
        var revoked=store.state
        revoked.flags.remove(VeilArchive.discovery)
        XCTAssertTrue(VeilCommunity.bookmarkIDs(revoked).isEmpty)
        XCTAssertNil(LumaAssistantEvidence.selected("veil:thread:quiet-tapes",in:revoked))
        for id in ["ordinary-hours","favorite-frame","not-a-relationship"] {
            XCTAssertNil(VeilCommunity.thread(id,in:revoked))
        }
    }
}
